"""Evaluate baseline and temporal-feature models on a labelled synthetic benchmark.
Synthetic metrics do not estimate real-world accuracy on unlabelled GitHub data.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.ensemble import IsolationForest
from sklearn.metrics import accuracy_score, average_precision_score, confusion_matrix, f1_score, precision_score, recall_score, roc_auc_score
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import RobustScaler

BASE = ["event_count", "distinct_repositories", "normalized_repo_entropy"]
TEMPORAL = ["repository_transitions", "transitions_per_observed_span_hour", "short_horizon_reentry_rate"]
EXTENDED = BASE + TEMPORAL
LABEL = "synthetic_high_fragmentation"

def make_data(n, seed):
    rng = np.random.default_rng(seed)
    y_seed = rng.binomial(1, 0.20, n)
    events = rng.negative_binomial(2, np.where(y_seed == 1, 0.40, 0.48)) + 1
    repos = 1 + rng.poisson(np.where(y_seed == 1, 2.0, 0.65))
    entropy = np.clip(rng.beta(np.where(y_seed == 1, 3.0, 1.2), np.where(y_seed == 1, 1.8, 4.0)), 0, 1)
    transitions = rng.poisson(np.where(y_seed == 1, 2.4 + 0.55 * repos, 0.25 + 0.30 * repos))
    span = np.maximum(rng.gamma(2.0, 5.0, n), 1.0)
    intensity = transitions / span
    reentry = np.clip(rng.beta(np.where(y_seed == 1, 2.4, 0.8), np.where(y_seed == 1, 3.0, 7.0)) + rng.normal(0, 0.07, n), 0, 1)
    latent = 0.75*(entropy > .55) + .70*(transitions >= 4) + .55*(reentry > .25) + .20*(repos >= 3) + rng.normal(0, .85, n)
    score = latent + .65*y_seed
    threshold = np.quantile(score, .80)
    labels = (score >= threshold).astype(int)
    return pd.DataFrame({
        "event_count": events, "distinct_repositories": repos,
        "normalized_repo_entropy": entropy, "repository_transitions": transitions,
        "transitions_per_observed_span_hour": intensity,
        "short_horizon_reentry_rate": reentry, LABEL: labels
    })

def scaled(train, val, test, features):
    scaler = RobustScaler()
    return (scaler.fit_transform(train[features].astype(float)),
            scaler.transform(val[features].astype(float)),
            scaler.transform(test[features].astype(float)))

def threshold_from_validation(y, scores):
    candidates = np.unique(np.quantile(scores, np.linspace(.50, .995, 100)))
    best_t, best_f1 = float(candidates[0]), -1.0
    for t in candidates:
        current = f1_score(y, (scores >= t).astype(int), zero_division=0)
        if current > best_f1:
            best_t, best_f1 = float(t), float(current)
    return best_t, best_f1

def evaluate(name, y, scores, threshold, val_f1, n_features):
    pred = (scores >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()
    return {
        "model": name, "feature_count": n_features,
        "validation_f1_at_selected_threshold": val_f1,
        "threshold_selected_on_validation": threshold,
        "test_accuracy": accuracy_score(y, pred),
        "test_precision": precision_score(y, pred, zero_division=0),
        "test_recall": recall_score(y, pred, zero_division=0),
        "test_f1": f1_score(y, pred, zero_division=0),
        "test_roc_auc": roc_auc_score(y, scores),
        "test_average_precision": average_precision_score(y, scores),
        "true_negative": int(tn), "false_positive": int(fp),
        "false_negative": int(fn), "true_positive": int(tp),
    }, pred

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--samples", type=int, default=20000)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", default="reports/synthetic_evaluation")
    parser.add_argument("--contamination", type=float, default=.20)
    args = parser.parse_args()
    if args.samples < 1000:
        parser.error("--samples must be at least 1000")
    if not .01 <= args.contamination <= .40:
        parser.error("--contamination must be between .01 and .40")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    data = make_data(args.samples, args.seed)
    data.to_csv(out / "synthetic_benchmark_dataset.csv", index=False)
    y = data[LABEL].to_numpy(dtype=int)
    trainval, test = train_test_split(data, test_size=.15, random_state=args.seed, stratify=y)
    train, val = train_test_split(trainval, test_size=(.15/.85), random_state=args.seed, stratify=trainval[LABEL])
    y_val = val[LABEL].to_numpy(dtype=int)
    y_test = test[LABEL].to_numpy(dtype=int)
    print(f"Synthetic records: {len(data):,}; train: {len(train):,}; validation: {len(val):,}; test: {len(test):,}")
    print(f"Synthetic label prevalence: {y.mean():.3f}")
    print("Warning: labels are generated by synthetic rules, not verified labels for real developers.")
    rows, predictions = [], pd.DataFrame({"test_row_index": test.index, "y_true_synthetic": y_test})
    for name, features in [("baseline", BASE), ("extended", EXTENDED), ("temporal_only_ablation", TEMPORAL)]:
        print(f"\nTraining {name} Isolation Forest ({len(features)} features)...", flush=True)
        x_train, x_val, x_test = scaled(train, val, test, features)
        model = IsolationForest(n_estimators=200, contamination=args.contamination, random_state=args.seed, n_jobs=-1)
        model.fit(x_train)
        val_scores = -model.decision_function(x_val)
        test_scores = -model.decision_function(x_test)
        threshold, val_f1 = threshold_from_validation(y_val, val_scores)
        row, pred = evaluate(name, y_test, test_scores, threshold, val_f1, len(features))
        rows.append(row)
        predictions[f"{name}_score"] = test_scores
        predictions[f"{name}_prediction"] = pred
        cm = confusion_matrix(y_test, pred, labels=[0,1])
        fig, ax = plt.subplots(figsize=(5.5,4.5))
        im = ax.imshow(cm)
        ax.set_title(f"{name.replace('_',' ').title()} — synthetic test")
        ax.set_xlabel("Predicted label")
        ax.set_ylabel("Synthetic reference label")
        ax.set_xticks([0,1], ["Normal", "High fragmentation"])
        ax.set_yticks([0,1], ["Normal", "High fragmentation"])
        for (i,j), v in np.ndenumerate(cm):
            ax.text(j, i, f"{v:,}", ha="center", va="center")
        fig.colorbar(im, ax=ax, label="Records")
        fig.tight_layout()
        fig.savefig(out / f"{name}_confusion_matrix.png", dpi=160)
        plt.close(fig)
        print(f"Test: accuracy={row['test_accuracy']:.3f}, precision={row['test_precision']:.3f}, recall={row['test_recall']:.3f}, F1={row['test_f1']:.3f}, ROC-AUC={row['test_roc_auc']:.3f}", flush=True)
    pd.DataFrame(rows).to_csv(out / "synthetic_test_metrics.csv", index=False)
    predictions.to_csv(out / "synthetic_test_predictions.csv", index=False)
    print(f"\nSaved outputs to: {out.resolve()}")
    print("Includes synthetic dataset, test metrics, predictions, and confusion matrices.")
    print("Use these metrics only for the defined synthetic benchmark; they do not validate real-data accuracy.")

if __name__ == "__main__":
    main()
